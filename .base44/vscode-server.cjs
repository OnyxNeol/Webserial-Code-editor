const DENIED_PAGE_HTML = `<!DOCTYPE html>
<html lang="en">
<head><meta charset="utf-8"><title>Access Denied</title></head>
<body style="font-family:system-ui;background:#1e1e1e;color:#ccc;display:flex;align-items:center;justify-content:center;min-height:100vh;margin:0">
<div style="text-align:center">
<h1 style="color:#f48771">Access Denied</h1>
<p>The link is invalid or has expired. Ask the AI for a new workspace link.</p>
</div>
</body></html>`;

(async () => {
  const app = await createApp({ build: { type: 'sources', location: '/vscode' }, printServerLog: false, coi: false, esm: true });

  if (process.env.BASE44_PREVIEW_MODE === '1') {
    app.proxy = true;
  }

  // Single middleware that runs before all existing middleware (router, static, etc.)
  app.middleware.unshift(async (ctx, next) => {
    // 1. Token-based access control (always active)
    const token = (ctx.query && ctx.query.token) || parseCookie(ctx.headers.cookie, 'vs_ws_token');

    if (token) {
      const valid = await validateToken(token);
      if (valid) {
        // Set cookie so subsequent requests (JS/CSS/assets) pass without the query param
        ctx.set('Set-Cookie', `vs_ws_token=${token}; HttpOnly; Path=/; Max-Age=86400; SameSite=Lax`);
      } else {
        ctx.status = 403;
        ctx.type = 'text/html';
        ctx.body = DENIED_PAGE_HTML;
        return;
      }
    } else {
      // No token — block access
      const accept = ctx.headers.accept || '';
      const isPage = accept.includes('text/html') || ctx.path === '/' || ctx.path === '/index.html';
      if (isPage) {
        ctx.status = 403;
        ctx.type = 'text/html';
        ctx.body = ACCESS_PAGE_HTML;
        return;
      } else {
        ctx.status = 403;
        ctx.body = 'Access required';
        return;
      }
    }

    // 2. Preview-mode specific logic
    if (process.env.BASE44_PREVIEW_MODE === '1') {
      // Serve extracted inline scripts as external JS files
      if (ctx.path.startsWith('/inline-scripts/') && ctx.path.endsWith('.js')) {
        const hash = ctx.path.split('/').pop().replace('.js', '');
        const content = inlineScriptCache.get(hash);
        if (content) {
          ctx.set('Content-Type', 'application/javascript');
          ctx.set('Cache-Control', 'no-store');
          ctx.body = content;
          return;
        }
      }

      // Normalize the origin for the HTTPS preview proxy
      if (process.env.BASE44_PUBLIC_HOST_SUFFIX) {
        ctx.req.headers['x-forwarded-host'] = `3000-${process.env.BASE44_PUBLIC_HOST_SUFFIX}`;
        ctx.req.headers['x-forwarded-proto'] = 'https';
      }
    }

    // 3. Run all existing middleware (workbench router, static files, etc.)
    await next();

    // 4. After the response is generated, extract inline scripts from HTML (preview mode only)
    if (process.env.BASE44_PREVIEW_MODE === '1') {
      const ct = ctx.type || '';
      if (ct.includes('html') && typeof ctx.body === 'string' && ctx.body.includes('<script>')) {
        ctx.body = extractInlineScripts(ctx.body);
      }
    }
  });

  const port = Number(process.env.PORT || 3000);
  app.listen(port, '0.0.0.0', () => console.log(`Official VS Code source-mode server listening on port ${port}`));
})().catch(error => { console.error(error); process.exit(1); });
